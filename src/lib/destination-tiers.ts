export function classifyDestination(destination: string): DestinationTier {
  const value = (destination || '').trim();
  if (!value || value === '其他') return 'more';
  if (NEARBY_DESTINATIONS.has(value)) return 'nearby';
  if (PROVINCE_LEVEL.has(value)) return 'province';
  if (OVERSEAS.has(value)) return 'overseas';
  // 长度≥4 的中文地名多半是县/市全称（如"恩施土家族苗族自治州"），归国内更稳。
  if (value.length >= 4) return 'domestic';
  return 'more';
}

/** 按分层返回目的地，保持调用方给的排序（默认按线路数降序）。 */
export function groupDestinationsByTier(destinations: string[]) {
  const grouped: Record<DestinationTier, string[]> = {
    nearby: [],
    province: [],
    domestic: [],
    overseas: [],
    more: [],
  };
  for (const destination of destinations) {
    grouped[classifyDestination(destination)].push(destination);
  }
  return grouped;
}

