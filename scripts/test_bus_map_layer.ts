import assert from 'node:assert/strict';
import { busMapLevel, isBusMapPoint, limitBusMapRoutes, limitBusMapStops } from '../src/lib/bus-map-layer';
import type { BusLine } from '../src/types/bus';

const line: BusLine = { id: 'reverse', name: '乙到甲', originCity: '乙市', destinationCity: '甲市', coordinateSystem: 'wgs84', stops: [], departTimes: [], priceFen: null };
assert.equal(isBusMapPoint({ lat: NaN, lng: 113 }), false);
assert.equal(isBusMapPoint({ lat: 0, lng: 113 }), false);
assert.equal(busMapLevel(7, true), 'focused');
assert.deepEqual([7, 8, 11].map((zoom) => busMapLevel(zoom, false)), ['overview', 'routes', 'stops']);
const routes = Array.from({ length: 100 }, (_, i) => ({ line: { ...line, id: String(i) }, distance: 100 - i }));
assert.equal(limitBusMapRoutes(routes, 'overview').length, 60, 'restore the province network budget');
assert.equal(limitBusMapRoutes(routes, 'routes').length, 80, 'restore the medium zoom network budget');
assert.equal(limitBusMapRoutes(routes.slice(0, 24), 'stops').length, 24, 'do not cut a moderately populated local network');
const horizontal = (y: number): [{ x: number; y: number }, { x: number; y: number }] => [{ x: 0, y }, { x: 200, y }];
const spread = routes.slice(0, 40).map((route, i) => ({ ...route, visibleSegments: [horizontal(i * 16)] }));
assert.equal(limitBusMapRoutes(spread, 'stops').length, 40, 'distinct corridors must survive the old 32-line cap');
const duplicate = { ...spread[0], distance: 0, visibleSegments: [horizontal(3)], line: { ...line, id: 'duplicate' } };
const crossing = { ...duplicate, visibleSegments: [[{ x: 100, y: 0 }, { x: 100, y: 200 }]] as typeof duplicate.visibleSegments, line: { ...line, id: 'crossing' } };
assert.deepEqual(limitBusMapRoutes([spread[0], duplicate, crossing], 'stops').map(({ line }) => line.id), ['crossing', 'duplicate']);
const branch = { ...duplicate, distance: 1, visibleSegments: [horizontal(3), [{ x: 200, y: 3 }, { x: 230, y: 50 }]] as typeof duplicate.visibleSegments, line: { ...line, id: 'branch' } };
assert.equal(limitBusMapRoutes([duplicate, branch], 'stops').length, 2, 'preserve a real branch off a shared corridor');
assert.equal(limitBusMapRoutes([duplicate, { ...crossing, distance: Infinity }], 'stops').length, 1);
assert.equal(limitBusMapRoutes(routes, 'overview', true).length, 100, 'a selected city bypasses the overview budget');
assert.equal(limitBusMapRoutes([spread[0], duplicate], 'stops', true).length, 2, 'selected routes are not merged at close zoom');
assert.equal(limitBusMapRoutes([{ ...duplicate, distance: Infinity }], 'stops', true).length, 1, 'selected offscreen geometry remains in the layer');
const { busLineWeight, matchesBusCities } = await import('../src/lib/bus-map-layer');
assert.equal(matchesBusCities('甲市', '乙市', ['甲市'], ['乙市', '丙市']), true);
assert.equal(matchesBusCities('甲市', '丁市', ['甲市'], ['乙市']), false);
assert.equal(matchesBusCities('丁市', '乙市', ['甲市'], ['乙市']), false);
assert.equal(matchesBusCities('甲市', undefined, ['甲市'], []), true);
assert.equal(matchesBusCities('甲市', undefined, ['甲市'], ['乙市']), false);
for (const level of ['overview', 'routes', 'stops'] as const) {
  assert.equal(busLineWeight(level, 0), busLineWeight(level, 1));
  assert.equal(busLineWeight(level, 2), busLineWeight(level, 5));
  assert(busLineWeight(level, 1) < busLineWeight(level, 2));
  assert(busLineWeight(level, 5) < busLineWeight(level, 6));
  assert(busLineWeight(level, 6) < busLineWeight('focused', 1));
}
assert(busLineWeight('overview', 6) < busLineWeight('routes', 6));
for (const departures of [1, 2, 6]) {
  const baseWidth = departures === 1 ? 1 : departures === 2 ? 1.5 : 2.2;
  assert.equal(busLineWeight('overview', departures), 0.7 * baseWidth * 0.85);
  assert.equal(busLineWeight('routes', departures), baseWidth * 0.85);
}
assert.equal(busLineWeight('focused', 6, false), 5);
assert(busLineWeight('stops', 6) <= 1.5, 'dense high-zoom lines must be visibly thinner');
assert(busLineWeight('stops', 6, false) < busLineWeight('stops', 1), 'through lines should recede even when frequent');
assert(busLineWeight('stops', 1, false) < busLineWeight('stops', 6, false), 'through lines retain the frequency ranking');
const { busLineOpacity, hasVisibleBusStop } = await import('../src/lib/bus-map-layer');
assert.equal(busLineOpacity('overview', 7, false), 0.22);
assert.equal(busLineOpacity('routes', 10, false), 0.42);
assert.equal(busLineOpacity('focused', 18, false), 1);
assert(busLineOpacity('stops', 11, true) > busLineOpacity('stops', 11, false));
const { busThroughPaneOpacity } = await import('../src/lib/bus-map-layer');
assert(busThroughPaneOpacity(11) <= 0.25, 'stacked through lines must remain faint as a group');
assert(busThroughPaneOpacity(16) < busThroughPaneOpacity(11));
assert(busLineOpacity('stops', 16, false) * busThroughPaneOpacity(16) < busLineOpacity('stops', 11, false) * busThroughPaneOpacity(11));
const bounds = { left: 0, top: 0, right: 100, bottom: 100 };
const panel = { left: 60, top: 10, right: 100, bottom: 95 };
assert.equal(hasVisibleBusStop([{ x: 80, y: 50 }, null, { x: -2, y: 50 }], bounds, panel), false);
assert.equal(hasVisibleBusStop([{ x: 80, y: 50 }, { x: 30, y: 50 }], bounds, panel), true);
assert.equal(hasVisibleBusStop([{ x: 80, y: 50 }], bounds), true);
const stops = Array.from({ length: 50 }, (_, i) => ({ x: i * 20, y: 0, exact: true }));
assert.equal(limitBusMapStops(stops).length, 36);
assert.deepEqual(limitBusMapStops([{ x: 1, y: 1, exact: false }, stops[0]]), [stops[0]]);
console.log('[bus-map-layer] all assertions passed');
