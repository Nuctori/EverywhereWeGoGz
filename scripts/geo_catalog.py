def _find_direct_place_match(text):
    value = str(text or "").strip()
    exact_matches = [(alias, place) for alias, place in ALIAS_ROWS if alias == value]
    if exact_matches:
        alias, place = exact_matches[0]
        if alias == place["name"] or not _is_named_alias(alias, place["name"]):
            return place, place["name"]
    named_matches = [
        (alias, place)
        for alias, place in ALIAS_ROWS
        if _is_named_alias(alias, place["name"]) and alias in value
    ]
    if named_matches:
        alias, place = max(named_matches, key=lambda item: len(item[0]))
        label = alias if alias.startswith(place["name"]) else f"{place['name']}{alias}"
        return place, label
    place = find_place(value)
    return (place, place["name"]) if place else (None, "")


def _raw_destination_is_explicit_departure(title, label):
    """Reject a source destination only for an explicit departure phrase."""
    value = str(title or "")
    place = str(label or "")
    if not place or place not in value:
        return False
    escaped = re.escape(place)
    explicit_patterns = (
        rf"(?:从|由|自|在|于){escaped}(?:出发|起止|起程|直飞|直航|直达|联运)",
        rf"{escaped}(?:出发|起止|起程|直飞|直航|直达|联运)",
        rf"(?:{escaped})(?:[A-Za-z0-9]{{0,8}})(?:出发|起止|起程|直飞|直航|直达|联运)",
    )
    return any(re.search(pattern, value) for pattern in explicit_patterns)


# Foreign brand/ship/company names that collide with catalog city names as
# substrings (雅典娜号 ship, 罗马假日 brand, 威尼斯人 resort, 巴黎春天 mall).
# When a city alias is followed by one of these, the mention is a brand name,
# not a destination. Mirrors the D-007 维也纳 decision: curated exclusion set,
# zero collateral (a broad CJK-tail guard mis-pinned 91 legit international
# tours like 新加坡环球影城 / 加拿大落基山).
BRAND_CONTINUATIONS = {
    "雅典娜": "雅典",
    "罗马假日": "罗马",
    "威尼斯人": "威尼斯",
    "巴黎春天": "巴黎",
    "巴黎人": "巴黎",
    "巴黎轩": "巴黎",
    "伦敦人": "伦敦",
    "米兰达": "米兰",
}
# Context-sensitive brands: rejected only when the tour route is a domestic
# province (e.g. 澳门巴黎铁塔 on a 广东 tour), but kept on international routes
# (巴黎铁塔 = the real Eiffel Tower on 欧洲 tours).
CONTEXTUAL_BRANDS = {
    "巴黎铁塔": "巴黎",
}


def _iter_place_mentions(
    text,
    *,
    domestic_route: bool = False,
    poi_index_enabled: bool = False,
    in_title: bool = False,
):
    value = str(text or "")
    matches = []
    for alias, place in ALIAS_ROWS:
        start = 0
        while alias:
            index = value.find(alias, start)
            if index < 0:
                break
            end = index + len(alias)
            # Rhetorical mention in marketing copy: "不是巴黎卢浮宫去不起"
            # (not-Paris Louvre), "与纽约第五大道齐名" (ranked with New York),
            # "仿造巴黎街区样式" (Parisian-style blocks), "身处法国巴黎香榭
            # 丽舍大道" (like being in Paris), "'小伦敦'" (Nuwara Eliya's
            # nickname), "'马尔代夫'的阳西沙扒湾" (quoted metaphor),
            # "中国仙本那" (恩施屏山峡谷 nickname), "被誉为北方的西湖"
            # (metaphor) are comparisons, not destinations.
            if value[max(0, index - 2) : index] == "不是":
                start = index + 1
                continue
            before_char = value[max(0, index - 1) : index]
            # Quoted nickname "X的Y" inside quotes: "侗族的香格里拉" (三江侗乡
            # nickname) is not the Yunnan city — reject when 的-preceded AND the
            # phrase sits inside quotes. A bare 愉快的重庆之行 (no quotes) stays.
            if before_char == "的" and any(
                q in value[max(0, index - 24) : index]
                for q in ("“", "”", '"', "‘", "’", "'")
            ):
                start = index + 1
                continue
            if (
                before_char in ("小", "'", '"', "‘", "“")
                or (before_char == "古" and place.get("country") != "中国")
                or value[max(0, index - 2) : index] in ("被称", "称为", "称作")
                or (
                    before_char == "国"
                    and value[max(0, index - 2) : index] == "中国"
                    and place.get("country") != "中国"
                )
            ):
                start = index + 1
                continue
            rhetoric_before = value[max(0, index - 8) : index]
            # 无需转机/无需直飞 negates the flight tokens — keep the city
            # (仙本那「无需转机」is a real destination).
            negative_before = "无需" in rhetoric_before or "不用" in rhetoric_before
            if any(
                token in rhetoric_before
                for token in (
                    "身处",
                    "置身",
                    "宛如",
                    "仿佛",
                    "犹如",
                    "好像",
                    "仿若",
                    "誉为",
                    "称之",
                )
            ):
                start = index + 1
                continue
            # Flight-endpoint tokens (直飞/转机/经停) reject the city even in
            # titles: 上海直飞赫尔辛基 names a transit endpoint, not a
            # destination. Only negated by 无需/不用.
            if not negative_before and any(
                token in rhetoric_before for token in ("经停", "转机", "直飞")
            ):
                start = index + 1
                continue
            rhetoric_tail = value[end : end + 30]
            if not in_title and any(
                token in rhetoric_tail
                for token in (
                    "齐名",
                    "并称",
                    "共称",
                    "合称",
                    "统称",
                    "媲美",
                    "齐头",
                    "仿造",
                    "仿制",
                    "模仿",
                    "样式",
                    "类似",
                    "堪比",
                    "转机",
                    "航班",
                    "机场",
                    "飞行",
                    "经停",
                    "参考航班",
                    "总部",
                    "世家",
                    "相提并论",
                    "美誉",
                )
            ):
                start = index + 1
                continue
            # A catalog city name that prefixes a known foreign brand/ship name
            # (雅典娜号, 罗马假日) is a collision, not a destination mention.
            tail_run = value[end : end + 6]
            brand_pools = (
                BRAND_CONTINUATIONS if place.get("name") else {},
                CONTEXTUAL_BRANDS if domestic_route else {},
            )
            collision = False
            for pool in brand_pools:
                for brand in pool:
                    if pool[brand] != place.get("name"):
                        continue
                    remainder = brand[len(alias) :]
                    if (
                        brand.startswith(alias)
                        and remainder
                        and tail_run.startswith(remainder)
                    ):
                        collision = True
                        break
                if collision:
                    break
            if collision:
                start = index + 1
                continue
            # Continuation guard for ALIAS_ROWS cities too: 胡志明亭 (border
            # memorial at 东兴) is not 胡志明市; 羚羊峡 in 羚羊峡谷 is not the
            # 肇庆 gorge (POI_CONTINUATIONS, D-019 family). Check a window
            # around the mention so both 利马索尔 (利马 followed by 索尔) and
            # 斯利马 (利马 preceded by 斯) are caught.
            alias_window = value[max(0, index - 2) : end + 3]
            place_name = place.get("name") or ""
            if any(
                cont in alias_window
                for cont in (
                    POI_CONTINUATIONS.get(place_name, ())
                    + POI_CONTINUATIONS.get(alias, ())
                )
            ):
                start = index + 1
                continue
            matches.append(
                {
                    "place": place,
                    "alias": alias,
                    "start": index,
                    "end": end,
                }
            )
            start = index + 1
    # Scenic POIs from the metadata index (no ALIAS_ROWS row, no hard-coded
    # coordinate): mention them so the mined label flows to the geocoder.
    # Only when poi_index_enabled: a Chinese scenic name inside an
    # international tour title is a shorthand collision (羚羊峡 = Antelope
    # Canyon on US tours), not the 肇庆 gorge.
    if poi_index_enabled:
        for poi_name, (province, city) in DOMESTIC_POI_INDEX.items():
            start = 0
            while poi_name:
                index = value.find(poi_name, start)
                if index < 0:
                    break
                end = index + len(poi_name)
                # POI name is a substring of an unrelated word (羚羊峡 in
                # 羚羊峡谷, Antelope Canyon): reject the mention (D-019 pattern).
                tail = value[end : end + 1]
                if tail and tail in POI_CONTINUATIONS.get(poi_name, ()):
                    start = index + 1
                    continue
                matches.append(
                    {
                        "place": {
                            "name": poi_name,
                            "country": "中国",
                            "province": province,
                            "city": city,
                            "latitude": None,
                            "longitude": None,
                            "level": "poi",
                        },
                        "alias": poi_name,
                        "start": index,
                        "end": end,
                    }
                )
                start = index + 1
    matches.sort(key=lambda item: (item["start"], -len(item["alias"])))
    selected = []
    occupied_until = -1
    for item in matches:
        if item["start"] < occupied_until:
            continue
        # Same name at a different position is a DIFFERENT mention with its own
        # context (【新兴.直通车】新兴温德姆酒店): both survive so the
        # suffix-aware sort can pick 新兴温德姆酒店 over the bare 新兴.
        selected.append(item)
        occupied_until = item["end"]
    return selected


def _is_departure_mention(text, mention):
    value = str(text or "")
    start = mention["start"]
    end = mention["end"]
    after = value[end : min(len(value), end + 16)]
    after_text = after.lstrip()
    if after_text.startswith("往返") and mention["place"]["country"] != "中国":
        return False
    before_text = value[max(0, start - 16) : start].rstrip()
    if re.search(rf"(?:{DEPARTURE_CITY_PATTERN})$", before_text) and re.match(
        r"(?:往返|起止|起程|出发|直飞|直航|直达)",
        after_text,
    ):
        return False
    if DEPARTURE_MARKERS.match(after_text) or re.match(
        r"[A-Za-z0-9]{0,8}(?:起止|起程|出发|往返|直飞|直航|直达|集合|起飞|返程|回程|联运|双飞)",
        after_text,
    ):
        return True
    if re.match(r"(?:站|机场|港口)?(?:往返|起止|起程|出发)", after_text):
        return True
    if re.match(
        r"(?:市区|市内|机场|码头|车站|高铁站)(?:往返|接送|接驳|交通)", after_text
    ):
        return True
    if mention["alias"].endswith("市") and re.match(
        r"(?:区|内)(?:往返|接送|接驳|交通)", after_text
    ):
        return True
    if re.match(r"(?:南|北|东|西)?(?:起止|往返|起程|出发)", after_text):
        return True
    if re.match(
        rf"(?:{AIRLINE_CODES})(?=\s*(?:直飞|直航|往返|联运|航班|双飞|[()（）\[\]【】]|$))",
        after_text,
        re.IGNORECASE,
    ):
        return True
    if mention["place"]["name"] in DEPARTURE_CITY_NAMES and re.match(
        rf"(?:{AIRLINE_NAMES})(?:直飞|联运|航班|往返)?", after_text
    ):
        return True
    if re.match(
        rf"(?:[/／或和及、,，]?\s*(?:{DEPARTURE_CITY_PATTERN}))+\s*(?:多地)?(?:起止|起程|出发|往返|直飞|联运|双飞)",
        after_text,
    ):
        return True
    if re.search(
        rf"(?:{DEPARTURE_CITY_PATTERN})\s*[/／或和及、,，]\s*$", before_text
    ) and re.match(
        r"(?:起止|起程|出发|往返|直飞|联运|双飞)",
        after_text,
    ):
        return True
    if mention["place"]["name"] in DEPARTURE_CITY_NAMES and re.search(
        rf"(?:{AIRLINE_NAMES}|{AIRLINE_CODES})[^\u4e00-\u9fff]{{0,12}}$",
        before_text,
        re.IGNORECASE,
    ):
        return True
    if (
        mention["place"]["name"] in DEPARTURE_CITY_NAMES
        and re.search(
            rf"(?:{AIRLINE_NAMES}|{AIRLINE_CODES})\s*$", before_text, re.IGNORECASE
        )
        and re.match(
            r"(?:[-—－]?\s*(?:大兴|浦东|白云|萧山|马德里|法兰克福|赫尔辛基|直飞|直航|双直航))",
            after_text,
        )
    ):
        return True
    if re.match(r"(?:阪东|东阪|多地)", after_text):
        return True
    if re.match(r"(?:[-—－]\s*)", after) and re.search(
        rf"(?:{AIRLINE_CODES})\s*$",
        before_text,
        re.IGNORECASE,
    ):
        return True
    next_catalog_mention = next(
        (
            candidate
            for candidate in _iter_place_mentions(value)
            if candidate["start"] >= end
            and candidate["start"] - end <= 8
            and candidate["place"]["name"] != mention["place"]["name"]
        ),
        None,
    )
    next_catalog_gap = (
        value[end : next_catalog_mention["start"]] if next_catalog_mention else ""
    )
    if (
        mention["place"]["name"] in DEPARTURE_CITY_NAMES
        and next_catalog_mention
        and re.fullmatch(r"\s*[-—－/／或和及、,，]?\s*", next_catalog_gap)
        and not re.match(r"(?:塔|广场|花城|南沙)", after_text)
    ):
        return True
    if re.match(r"[【\[]", after_text):
        return True
    if re.search(rf"(?:{AIRLINE_CODES})\s*[-—－]\s*$", before_text, re.IGNORECASE):
        return True
    dash_match = re.match(r"\s*[-—－]\s*", after)
    if dash_match:
        dash_tail = after[dash_match.end() :]
        immediate_match = re.match(r"[\u4e00-\u9fff]+", dash_tail)
        immediate = immediate_match.group(0) if immediate_match else ""
        inline_alias = mention["alias"] != mention["place"]["name"] and value[
            :start
        ].rstrip().endswith(mention["place"]["name"])
        if mention["place"]["name"] in DEPARTURE_CITY_NAMES and (
            any(alias and immediate.startswith(alias) for alias, _ in ALIAS_ROWS)
            or inline_alias
        ):
            return True
        if mention["place"]["name"] in DEPARTURE_CITY_NAMES and find_region(dash_tail):
            return True
    before = value[max(0, start - 8) : start]
    if re.search(r"(?:从|由|自|在|于)\s*$", before):
        return True
    return False


def _place_label(text, mention):
    value = str(text or "")
    alias = mention["alias"]
    canonical_name = mention["place"]["name"]
    if _is_named_alias(alias, canonical_name):
        prefix = (
            f"{canonical_name}{alias}"
            if not alias.startswith(canonical_name)
            else alias
        )
        tail_match = re.match(r"[\u4e00-\u9fff]{0,18}", value[mention["end"] :])
        tail = tail_match.group(0) if tail_match else ""
        suffix_matches = list(PLACE_LABEL_SUFFIXES.finditer(tail))
        if suffix_matches and suffix_matches[0].start() == 0:
            return f"{prefix}{tail[: suffix_matches[0].end()]}".strip()
        return prefix
    end = mention["end"]
    tail_match = re.match(r"[\u4e00-\u9fff]{0,18}", value[end:])
    tail = tail_match.group(0) if tail_match else ""
    suffix_matches = list(PLACE_LABEL_SUFFIXES.finditer(tail))
    suffix_match = suffix_matches[-1] if suffix_matches else None
    if tail.startswith(("回", "返", "去", "返回")):
        return mention["place"]["name"]
    if suffix_match:
        return f"{canonical_name}{tail[: suffix_match.end()]}".strip()
    return canonical_name


def _new_geo_resolution(destination, title, detail):
    detail = detail if isinstance(detail, dict) else {}
    itinerary_value = detail.get("itinerary")
    itinerary = itinerary_value if isinstance(itinerary_value, list) else []
    highlights_value = detail.get("highlights")
    highlights = highlights_value if isinstance(highlights_value, list) else []
    return {
        "input": {
            "destination": str(destination or "").strip(),
            "hasTitle": bool(str(title or "").strip()),
            "itineraryDays": len(itinerary),
            "accommodationDays": sum(
                1
                for day in itinerary
                if isinstance(day, dict) and str(day.get("accommodation") or "").strip()
            ),
            "highlightCount": sum(
                1 for value in highlights if str(value or "").strip()
            ),
        },
        "mining": {
            "status": "not-run",
            "candidateLabels": [],
            "candidateSources": [],
            "rejectedLabels": [],
            "reasons": [],
        },
        "osm": {"status": "not-run"},
        "geocoder": {"status": "not-run", "queries": []},
        "final": {"status": "unmapped"},
    }


def _append_unique(values, value):
    value = str(value or "").strip()
    if value and value not in values:
        values.append(value)


def mine_destination_place(raw, title, destination, detail=None, resolution=None):
    """Extract a named destination from title/detail text without treating departure as destination."""
    destination_text = str(destination or "").strip()
    resolution = (
        resolution
        if isinstance(resolution, dict)
        else _new_geo_resolution(destination_text, title, detail)
    )
    mining = resolution.setdefault("mining", {})
    # Re-mine from scratch every rebuild: a stale geoResolution.mining from a
    # previous round (e.g. 威海 candidateLabels on a 挪威 cruise) must not
    # survive as evidence after purge — the fixed tour would re-anchor the
    # wrong pin (D-016 fix-before-rebuild).
    mining.pop("candidateLabels", None)
    mining.pop("rejectedLabels", None)
    mining.pop("reasons", None)
    mining.pop("sourceCandidates", None)
    # 港澳/广东 can be departure placeholders on international tours, so only
    # real domestic provinces (province == name) gate the contextual brands
    # (e.g. 澳门巴黎铁塔 on a 广东 tour vs the real Eiffel Tower on 欧洲 tours).
    # The scenic-POI index (DOMESTIC_POI_INDEX) is disabled only on explicitly
    # international routes (country != 中国): dest=其他/全国/空 defaults to
    # domestic so 蓝钟/天露山 still resolve on tours without a province.
    destination_region = find_region(destination_text)
    title_region = find_region(str(title or ""))
    destination_international = bool(
        destination_region
        and destination_region.get("country")
        and str(destination_region.get("country")) != "中国"
    )
    title_international = bool(
        title_region
        and title_region.get("country")
        and str(title_region.get("country")) != "中国"
    )
    domestic_route = not (destination_international or title_international)
    # Two DIFFERENT gates: the brand guard (CONTEXTUAL_BRANDS 巴黎铁塔) keeps
    # its original "province == name" meaning so a real 巴黎铁塔 on a
    # dest=其他 international tour (tour_4716 法瑞意) is NOT suppressed;
    # the scenic-POI index uses the broader not-international gate so
    # 蓝钟/天露山 still resolve on dest=其他 domestic tours.
    brand_guard_domestic = bool(
        destination_region
        and destination_region.get("province")
        and destination_region.get("province") == destination_region.get("name")
    )
    poi_index_enabled = domestic_route
    title_departure_names = {
        mention["place"]["name"]
        for mention in _iter_place_mentions(
            title,
            domestic_route=brand_guard_domestic,
            poi_index_enabled=poi_index_enabled,
            in_title=True,
        )
        if _is_departure_mention(title, mention)
    }
    direct_place, direct_label = _find_direct_place_match(destination_text)
    if direct_place and direct_place["name"] not in title_departure_names:
        materialized = _materialize_named_place(direct_place, direct_label)
        mining["status"] = (
            "resolved" if materialized.get("latitude") is not None else "no-coordinate"
        )
        _append_unique(mining.setdefault("candidateLabels", []), direct_label)
        _append_unique(mining.setdefault("candidateSources", []), "destination")
        if materialized.get("latitude") is None:
            _append_unique(
                mining.setdefault("reasons", []),
                "named-alias-without-trusted-coordinate",
            )
        return materialized, direct_label, "medium", "local-place-catalog"
    if (
        direct_place
        and direct_place["name"] in title_departure_names
        and _raw_destination_is_explicit_departure(
            title,
            direct_label,
        )
    ):
        _append_unique(mining.setdefault("rejectedLabels", []), direct_label)
        _append_unique(
            mining.setdefault("reasons", []), "destination-matches-departure"
        )
    elif direct_place:
        materialized = _materialize_named_place(direct_place, direct_label)
        mining["status"] = (
            "resolved" if materialized.get("latitude") is not None else "no-coordinate"
        )
        _append_unique(mining.setdefault("candidateLabels", []), direct_label)
        _append_unique(mining.setdefault("candidateSources", []), "destination")
        return materialized, direct_label, "medium", "local-place-catalog"

    texts = [str(title or "")]
    detail = detail if isinstance(detail, dict) else {}
    for day in detail.get("itinerary") or []:
        if not isinstance(day, dict):
            continue
        # Merge day title + description into ONE text: a bare transit-hub
        # title (伊斯坦布尔 on the final 转机 day) then sees the flight info
        # (机场/参考航班) in its tail and is rejected by the rhetoric guard.
        day_title = str(day.get("title") or "")
        day_desc = str(day.get("description") or "")
        texts.append(f"{day_title} {day_desc}".strip() or day_title)
        texts.extend(str(value or "") for value in day.get("activities") or [])
    texts.extend(str(value or "") for value in detail.get("highlights") or [])

    candidates = []
    for text_index, text in enumerate(texts):
        # Flight-segment day titles (上海-(飞机)-伊斯坦布尔) name a transit
        # hub, not a destination — skip the whole short title.
        flight_segment_title = (
            text_index > 0
            and len(text) < 24
            and any(token in text for token in ("飞机", "航班", "转机", "机场"))
        )
        if flight_segment_title:
            continue
        # 游览语境 hard rule (D-029 宁缺毋滥, auditor 处方③): a foreign detail
        # mention on a day with NO sightseeing context (机上餐食/夜宿飞机/
        # 航班段) is a transit stop, not a destination — reject it so the tour
        # falls back to unmapped instead of pinning the transit hub. Sightseeing
        # days (里约市区游览) and title mentions keep their cities.
        has_sightseeing_context = any(
            token in text
            for token in (
                "游览",
                "参观",
                "观光",
                "漫步",
                "游玩",
                "探访",
                "市区",
                "景点",
                "游船",
                "逛街",
                "打卡",
            )
        )
        if (
            text_index > 0
            and not has_sightseeing_context
            and any(country in str(title or "") for country in INTERNATIONAL_COUNTRIES)
            and not any(country in text for country in INTERNATIONAL_COUNTRIES)
        ):
            # A day with an international-city mention but zero sightseeing
            # context (上海-(飞机)-伊斯坦布尔 / 伊斯坦布尔 + 夜宿飞机) is a
            # flight segment — skip its mentions.
            continue
        for mention in _iter_place_mentions(
            text,
            domestic_route=brand_guard_domestic,
            poi_index_enabled=poi_index_enabled,
            in_title=(text_index == 0),
        ):
            label = _place_label(text, mention)
            if mention["place"]["name"] in title_departure_names:
                _append_unique(mining.setdefault("rejectedLabels", []), label)
                _append_unique(mining.setdefault("reasons", []), "departure-mention")
                continue
            if _is_departure_mention(text, mention):
                _append_unique(mining.setdefault("rejectedLabels", []), label)
                _append_unique(mining.setdefault("reasons", []), "departure-mention")
                continue
            # Template pollution guard: an INTERNATIONAL title (加拿大/美国…)
            # whose detail mentions a DOMESTIC China place (新丰温德姆花园酒店)
            # is itinerary-template text, not a destination. The reverse
            # direction (国内 title + 国外 detail mention) stays legal
            # (D-007 pattern: 广东出发国际线). With NO region anchor at all
            # (title 东三省, dest=其他), detail mentions are unverifiable —
            # reject them too rather than pinning a 120km-away metaphor city.
            title_country = title_region.get("country") if title_region else None
            mention_country = mention["place"].get("country")
            # Only an EXPLICIT international country name in the title guards
            # against domestic template pollution (加拿大 tour + 新丰酒店).
            # China provinces/macro-regions and their shorthand (青甘/华东…)
            # must NOT trigger it — 青甘 tour + 敦煌莫高窟 is a real trip.
            # Use the substring scan, not find_region: the region table maps
            # 【庞洛邮轮船票·欧洲】 tour titles to 欧洲 (not 挪威), which would
            # let a domestic 威海 detail mention survive on a 挪威 cruise.
            title_country_is_international = bool(
                title_country in INTERNATIONAL_COUNTRIES
                or any(
                    country in str(title or "") for country in INTERNATIONAL_COUNTRIES
                )
            )
            # A direct substring scan is more reliable than find_region: the
            # region table lacks some countries (新西兰/加拿大…) and "中国国航
            # -全国联运" prefixes make find_region return 中国 first, hiding the
            # real international route (美国东西海岸). Substring detection sees
            # both and keeps foreign mentions on real international lines.
            title_has_international = any(
                country in str(title or "") for country in INTERNATIONAL_COUNTRIES
            )
            # Reverse direction: a DOMESTIC title (河南/华东… no international
            # signal) whose detail mentions a FOREIGN place (巴厘岛酒店 brand on
            # a 河南 tour) is brand/template text — reject it (D-019 family).
            # Gated on a REAL domestic-province destination: dest=其他/无锚定
            # keeps foreign mentions (四王群岛 tour + 巴厘岛 = real stops).
            if (
                text_index > 0
                and not title_has_international
                and destination_region
                and destination_region.get("province")
                and mention_country
                and mention_country != "中国"
                and mention_country not in ("中国香港", "香港", "澳门")
            ):
                _append_unique(mining.setdefault("rejectedLabels", []), label)
                _append_unique(
                    mining.setdefault("reasons", []), "title-region-conflict"
                )
                continue
            if text_index > 0 and (
                title_country_is_international and mention_country == "中国"
            ):
                _append_unique(mining.setdefault("rejectedLabels", []), label)
                _append_unique(
                    mining.setdefault("reasons", []), "title-region-conflict"
                )
                continue
            # Cross-country detail mention on an international tour: a 南美 tour
            # (title 巴西/秘鲁…) whose detail mentions 伊斯坦布尔/纽约/巴黎 is
            # a transit hub or rhetorical reference, not a destination. ALL
            # international countries named in the title are anchors (新马 tour
            # keeps both 新加坡 and 马来西亚); other-country mentions rejected.
            title_main_countries = {
                c for c in INTERNATIONAL_COUNTRIES if c in str(title or "")
            }
            if (
                text_index > 0
                and title_main_countries
                and mention_country
                and mention_country != "中国"
                and mention_country not in title_main_countries
                and mention_country not in ("中国香港", "香港", "澳门")
            ):
                # Cross-country detail mentions on an international tour are
                # transit hubs or rhetorical references (巴黎 on a 南美 tour),
                # never destinations — reject regardless of day context
                # (宁缺毋滥 D-029). Real multi-country routes name ALL their
                # countries in the title.
                _append_unique(mining.setdefault("rejectedLabels", []), label)
                _append_unique(
                    mining.setdefault("reasons", []), "title-country-conflict"
                )
                continue
            is_named_place = _is_inline_named_alias(text, mention) or (
                mention["alias"] == mention["place"]["name"]
                and mention["place"]["name"] in EXPLICIT_TITLE_DESTINATION_NAMES
            )
            candidates.append(
                (
                    text_index,
                    mention["start"],
                    mention["place"],
                    label,
                    is_named_place,
                )
            )

    raw_candidate_count = len(candidates)
    title_candidates = [item for item in candidates if item[0] == 0]
    if not title_candidates:
        candidates = [item for item in candidates if item[4]]
    for candidate in candidates:
        _append_unique(mining.setdefault("candidateLabels", []), candidate[3])
        source = "title" if candidate[0] == 0 else "detail"
        _append_unique(mining.setdefault("candidateSources", []), source)

    if not candidates:
        mining["status"] = "no-candidate"
        _append_unique(
            mining.setdefault("reasons", []),
            "no-catalog-mention" if raw_candidate_count == 0 else "no-named-candidate",
        )
        return None, "", "low", "unknown"
    region = find_region(destination_text)
    if region and region.get("province"):
        in_region = [
            item
            for item in candidates
            if item[2].get("province") == region["province"]
            and item[2].get("country") == region.get("country")
        ]
        named_in_region = [item for item in in_region if item[4]]
        named_anywhere = [item for item in candidates if item[4]]
        if named_in_region:
            candidates = in_region
        elif named_anywhere:
            # Source destination fields often contain the departure province;
            # an explicit named POI in the title is stronger evidence.
            candidates = named_anywhere
        elif in_region:
            first_candidate = min(candidates, key=lambda item: (item[0], item[1]))
            candidates = in_region if first_candidate in in_region else []
        else:
            # Some feeds copy the departure province into destination. When
            # no same-region candidate survives departure filtering, the first
            # remaining catalog place is the strongest title-level signal.
            pass
    named_candidates = [item for item in candidates if item[4]]
    if named_candidates:
        # A curated scenic POI (七星岩/鼎湖山/紫云谷/蓝钟) is more specific than
        # the parent city it sits in; when both appear in the title, the POI
        # wins even though the city textually comes first (肇庆2天＊鼎湖山).
        # Deliberately a WHITELIST, not EXPLICIT_POI_NAMES: the broad set also
        # contains independent destinations (沙巴/美奈/棉花堡/卡帕多奇亚) that
        # must NOT outrank the title's first city on international tours.
        poi_named = [
            item
            for item in named_candidates
            if item[2].get("name") in POI_OVER_CITY_PRIORITY
        ]
        candidates = poi_named if poi_named else named_candidates
    elif not candidates and destination_text not in {"", "其他", "全国"}:
        mining["status"] = "rejected"
        _append_unique(
            mining.setdefault("reasons", []), "no-region-compatible-candidate"
        )
        return None, "", "low", "unknown"
    candidates.sort(key=lambda item: (item[0], item[1]))
    _, _, place, label, _ = candidates[0]
    final_label = (
        label if named_candidates or label in NAMED_PLACE_COORDINATES else place["name"]
    )
    # NAMED_PLACE_COORDINATES candidates win (D-024 curation precedent): the
    # curated label has a trusted coordinate (姑婆山/白水寨). Otherwise pick the
    # first candidate that materializes — a POI-class label with no trusted
    # geometry (XX酒店 not in NAMED) must not degrade a poi tour to city.
    ordered = [
        candidate for candidate in candidates if candidate[3] in NAMED_PLACE_COORDINATES
    ] or candidates
    chosen_place = None
    chosen_label = ""
    for candidate in ordered:
        _, _, cand_place, cand_label, _ = candidate
        cand_final = (
            cand_label
            if named_candidates
            else (
                cand_label
                if cand_label in NAMED_PLACE_COORDINATES
                else cand_place["name"]
            )
        )
        cand_materialized = _materialize_named_place(cand_place, cand_final)
        if cand_materialized.get("latitude") is not None:
            chosen_place = cand_materialized
            chosen_label = cand_final
            break
    if chosen_place is None:
        chosen_place = _materialize_named_place(place, final_label)
        chosen_label = final_label
    materialized = chosen_place
    final_label = chosen_label
    mining["status"] = (
        "resolved" if materialized.get("latitude") is not None else "no-coordinate"
    )
    if materialized.get("latitude") is None:
        _append_unique(
            mining.setdefault("reasons", []), "named-alias-without-trusted-coordinate"
        )
    return materialized, final_label, "low", "title-place-miner"


def _prefer_existing_city_candidate(raw, resolution, current_place, current_label):
    """Prefer a named candidate anchored to the existing destination city."""
    if not isinstance(raw, dict) or not isinstance(resolution, dict):
        return current_place, current_label
    city = str(raw.get("destinationCity") or "").strip()
    if not city or city == str(raw.get("destination") or "").strip():
        return current_place, current_label
    country = str(raw.get("destinationCountry") or "").strip().lower()
    if country and country not in {"中国", "china", "cn"}:
        return current_place, current_label
    mining_value = resolution.get("mining")
    mining = mining_value if isinstance(mining_value, dict) else {}
    candidate_labels = mining.get("candidateLabels")
    labels = candidate_labels if isinstance(candidate_labels, list) else []
    for label in labels:
        label = str(label or "").strip()
        if not label or label == city or not label.startswith(city):
            continue
        place = find_place(label)
        if not place:
            continue
        return _materialize_named_place(place, label), label
    return current_place, current_label


def _raw_departure(raw):
    for key in ("departureCity", "departureProvince", "departureCountry"):
        if str(raw.get(key) or "").strip():
            return {
                key: str(raw[key]).strip()
                for key in ("departureCity", "departureProvince", "departureCountry")
                if str(raw.get(key) or "").strip()
            }, "source"
    nested = raw.get("departure") if isinstance(raw.get("departure"), dict) else {}
    if nested:
        values = {
            key: str(nested.get(key) or "").strip()
            for key in ("city", "province", "country")
            if str(nested.get(key) or "").strip()
        }
        if values:
            return {
                "departureCity": values.get("city", ""),
                "departureProvince": values.get("province", ""),
                "departureCountry": values.get("country", ""),
            }, "source"
    return {}, "unknown"


def normalize_tour_geo(raw, title, destination, detail=None):
    resolution = _new_geo_resolution(destination, title, detail)
    departure, departure_source = _raw_departure(raw)
    departure_place = None
    if not departure:
        for mention in _iter_place_mentions(title):
            if _is_departure_mention(title, mention):
                departure_place = mention["place"]
                departure = {
                    "departureCity": departure_place["name"],
                    "departureProvince": departure_place.get("province") or "",
                    "departureCountry": departure_place["country"],
                }
                departure_source = "inferred"
                break
    if not departure:
        for pattern in DEPARTURE_PATTERNS:
            match = pattern.search(str(title or ""))
            if match:
                departure_place = find_place(match.group(1))
                if departure_place:
                    departure = {
                        "departureCity": departure_place["name"],
                        "departureProvince": departure_place.get("province") or "",
                        "departureCountry": departure_place["country"],
                    }
                    departure_source = "inferred"
                    break
    if not departure_place and departure.get("departureCity"):
        departure_place = find_place(departure["departureCity"])
    if departure_place:
        departure.setdefault("departureProvince", departure_place.get("province") or "")
        departure.setdefault("departureCountry", departure_place["country"])

    destination_text = str(destination or "").strip()
    (
        destination_place,
        destination_label,
        destination_confidence,
        destination_geo_source,
    ) = mine_destination_place(
        raw,
        title,
        destination_text,
        detail,
        resolution,
    )
    preferred_place, preferred_label = _prefer_existing_city_candidate(
        raw,
        resolution,
        destination_place,
        destination_label,
    )
    if preferred_place is not destination_place and (
        destination_place is None or not destination_place.get("latitude")
    ):
        # Only fall back to the existing city anchor when mining produced no
        # coordinate — a fresh NAMED/curated pin (珠海东澳岛) must not be
        # overwritten by a stale destinationCity (广州南沙湾) from the source.
        destination_place = preferred_place
        destination_label = preferred_label
        destination_confidence = "low"
        destination_geo_source = "title-place-miner"
    destination_region = find_region(destination_text)
    # International title + departure-province destination: do NOT materialize
    # the departure region as a pin (斯里兰卡 tour with dest=广东 would show
    # 广东 region — D-007 占位). Leave it unmapped instead.
    title_region_here = find_region(str(title or ""))
    title_international_flag = bool(
        (
            title_region_here
            and title_region_here.get("country")
            and title_region_here.get("country") in INTERNATIONAL_COUNTRIES
        )
        or any(country in str(title or "") for country in INTERNATIONAL_COUNTRIES)
    )
    region_place = (
        None
        if title_international_flag
        else materialize_region(destination_region)
        if not destination_place
        else None
    )
    resolved_destination = destination_place or region_place
    resolved_label = (
        destination_label
        if destination_place
        else region_place.get("name", "")
        if region_place
        else ""
    )
    destination_country = (
        resolved_destination["country"] if resolved_destination else ""
    )
    destination_province = (
        (resolved_destination.get("province") or "") if resolved_destination else ""
    )
    destination_source = (
        "source" if str(raw.get("destination") or "").strip() else "inferred"
    )
    if region_place:
        resolution.setdefault(
            "fallback",
            {
                "status": "applied",
                "reason": "region-catalog-fallback",
                "level": region_place["level"],
            },
        )
    fields = {
        **departure,
        # POI places carry their parent city in the metadata index (七星岩 ->
        # 肇庆), so destinationCity is the parent city, not the POI name —
        # otherwise destination_queries sees label == city and never geocodes.
        "destinationCity": (
            resolved_destination.get("city") or resolved_destination["name"]
        )
        if resolved_destination
        else "",
        "destinationPlaceName": resolved_label,
        "destinationProvince": destination_province,
        "destinationCountry": destination_country,
        "destinationLatitude": resolved_destination["latitude"]
        if resolved_destination
        else None,
        "destinationLongitude": resolved_destination["longitude"]
        if resolved_destination
        else None,
        "destinationGeoLevel": _destination_level(destination_place, destination_label)
        if destination_place
        else region_place.get("level", "")
        if region_place
        else "",
        "destinationLocality": resolved_destination.get("locality", "")
        if resolved_destination
        else "",
        "destinationCoordinateSource": _destination_coordinate_source(
            destination_place, destination_label
        )
        if destination_place
        else "fallback"
        if region_place
        else "unknown",
        "destinationCoordinatePrecision": (
            "approximate"
            if region_place
            or (
                destination_place
                and _destination_level(destination_place, destination_label)
                in {"city", "country"}
            )
            else "exact"
            if destination_place and destination_place.get("latitude") is not None
            else None
        ),
        "geoStatus": "complete"
        if departure_place and resolved_destination
        else ("destination_only" if resolved_destination else "unmapped"),
        "geoConfidence": destination_confidence if destination_place else "low",
        "geoSource": destination_geo_source
        if destination_place
        else ("local-region-catalog" if region_place else "unknown"),
        "geoResolution": resolution,
    }
    existing_context = _existing_destination_context(raw, title)
    existing_source = (
        str(raw.get("destinationCoordinateSource") or "")
        if isinstance(raw, dict)
        else ""
    )
    if existing_context and not _valid_coordinate_pair(
        fields.get("destinationLatitude"), fields.get("destinationLongitude")
    ):
        fields["destinationCity"] = existing_context["city"]
        fields["destinationProvince"] = (
            existing_context["province"] or fields["destinationProvince"]
        )
        current_place = str(fields.get("destinationPlaceName") or "").strip()
        if not current_place or current_place == existing_context["city"]:
            fields["destinationPlaceName"] = existing_context["place"]
            current_place = existing_context["place"]
        fields["destinationGeoLevel"] = (
            "poi" if current_place != existing_context["city"] else "city"
        )
        if existing_source in {"catalog", "fallback"} and _valid_coordinate_pair(
            raw.get("destinationLatitude"), raw.get("destinationLongitude")
        ):
            for key in (
                "destinationLatitude",
                "destinationLongitude",
                "destinationLocality",
                "destinationCoordinateSource",
                "destinationCoordinatePrecision",
                "destinationAddress",
                "geoConfidence",
                "geoSource",
            ):
                if key in raw:
                    fields[key] = raw[key]
        else:
            fields["destinationLatitude"] = None
            fields["destinationLongitude"] = None
            fields["destinationCoordinateSource"] = "inferred"
            fields["destinationCoordinatePrecision"] = None
            fields["geoConfidence"] = "low"
            fields["geoSource"] = "existing-destination-context"
    if fields["destinationCoordinatePrecision"] is None:
        fields.pop("destinationCoordinatePrecision")
    if departure_place:
        fields.update(
            {
                "departureLatitude": departure_place["latitude"],
                "departureLongitude": departure_place["longitude"],
                "departureGeoLevel": "city",
                "departureLocality": "",
                "departureCoordinateSource": "catalog",
            }
        )
    return fields, {
        "departureCity": departure_source
        if departure.get("departureCity")
        else "unknown",
        "departureProvince": departure_source
        if departure.get("departureProvince")
        else "unknown",
        "departureCountry": departure_source
        if departure.get("departureCountry")
        else "unknown",
        "destinationCity": destination_source if resolved_destination else "unknown",
        "destinationPlaceName": "inferred" if resolved_destination else "unknown",
        "destinationProvince": "inferred" if resolved_destination else "unknown",
        "destinationCountry": "inferred" if resolved_destination else "unknown",
        "destinationLatitude": "inferred" if resolved_destination else "unknown",
        "destinationLongitude": "inferred" if resolved_destination else "unknown",
        "geoStatus": "inferred",
        "geoConfidence": "inferred",
        "geoSource": "inferred" if destination_place else "unknown",
        "routeRegion": "inferred",
    }


def classify_route(fields):
    country = fields.get("destinationCountry")
    departure_province = fields.get("departureProvince")
    destination_province = fields.get("destinationProvince")
    if not country or not departure_province:
        return "unknown"
    if country != "中国":
        return "international"
    if departure_province == destination_province:
        return "local"
    nearby_provinces = NEARBY_PROVINCES_BY_DEPARTURE.get(departure_province, set())
    if destination_province in nearby_provinces:
        return "nearby-province"
    return "national"
