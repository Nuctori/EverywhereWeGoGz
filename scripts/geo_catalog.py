def _is_named_alias(alias, canonical_name):
    """Treat catalog aliases as POIs unless they are administrative spellings."""
    return (
        bool(alias)
        and alias != canonical_name
        and not alias.endswith(ADMINISTRATIVE_ALIAS_SUFFIXES)
    )


def _is_inline_named_alias(text, mention):
    alias = mention["alias"]
    canonical_name = mention["place"]["name"]
    if not _is_named_alias(alias, canonical_name):
        return False
    if PLACE_LABEL_SUFFIXES.search(alias):
        return True
    if alias in EXPLICIT_NAMED_ALIASES:
        return True
    # Unique aliases remain useful destination evidence even when a source
    # inserts a city nickname, county, or marketing text before the alias.
    if ALIAS_PARENT_COUNTS.get(alias) == 1:
        return True
    prefix = str(text or "")[: mention["start"]].rstrip()
    # A catalog alias appearing after its canonical city is a named place,
    # even when the source inserts an unregistered county or town in between.
    return canonical_name in prefix


def _materialize_named_place(place, label):
    geometry = NAMED_PLACE_COORDINATES.get(label)
    if geometry:
        return {**place, **geometry}
    if label != place["name"]:
        # A named alias is more specific than its catalog parent. Until a
        # trusted geometry is available, keep the semantic place but do not
        # inherit the parent's city-centre coordinate.
        return {
            **place,
            "latitude": None,
            "longitude": None,
            "coordinateSource": "inferred",
        }
    return place


def _destination_level(place, label):
    if place.get("country") == place.get("name"):
        return "country"
    if place.get("level"):
        return place["level"]
    return (
        "poi"
        if label != place["name"] or place["name"] in EXPLICIT_POI_NAMES
        else "city"
    )


def _destination_coordinate_source(place, label):
    if place.get("coordinateSource"):
        return place["coordinateSource"]
    return "inferred" if _destination_level(place, label) == "poi" else "catalog"


def _existing_destination_context(raw, title):
    """Keep an evidence-backed city context across idempotent geo rebuilds."""
    if not isinstance(raw, dict) or not find_region(str(raw.get("destination") or "")):
        return None
    city = str(raw.get("destinationCity") or "").strip()
    place = str(raw.get("destinationPlaceName") or "").strip()
    province = str(raw.get("destinationProvince") or "").strip()
    if not city or city == str(raw.get("destination") or "").strip():
        return None
    labels = []
    resolution_value = raw.get("geoResolution")
    resolution = resolution_value if isinstance(resolution_value, dict) else {}
    mining_value = resolution.get("mining")
    mining = mining_value if isinstance(mining_value, dict) else {}
    candidate_labels = mining.get("candidateLabels")
    if isinstance(candidate_labels, list):
        labels = [
            str(label).strip() for label in candidate_labels if str(label).strip()
        ]
    title_text = str(title or "")
    has_evidence = (
        place != city
        and place in title_text
        or any(label != city and city in label for label in labels)
    )
    if not has_evidence:
        return None
    return {"city": city, "place": place or city, "province": province}


def find_place(text):
    value = str(text or "").strip()
